export function getSemesterOptions(year) {
  const firstSemester = (Number(year) - 1) * 2 + 1;
  if (!Number.isInteger(Number(year)) || Number(year) < 1 || Number(year) > 4) return [];
  return [firstSemester, firstSemester + 1].map((semester) => ({
    value: String(semester),
    label: `${semester}${semester === 1 ? 'st' : semester === 2 ? 'nd' : semester === 3 ? 'rd' : 'th'} semester`,
  }));
}
