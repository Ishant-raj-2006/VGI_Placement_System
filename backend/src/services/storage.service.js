import fs from 'node:fs/promises';
import { createReadStream } from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { Readable } from 'node:stream';
import { BlobNotFoundError, del, get, head, put } from '@vercel/blob';
import { config } from '../config/env.js';

/**
 * Private file storage. Files are NEVER served statically; every download goes through an
 * authorised API route which streams from here.
 *
 * To use S3 / GCS / Azure Blob in production, implement the same four functions
 * (saveFile, openStream, deleteFile, exists) and switch on STORAGE_DRIVER.
 */
const root = config.storage.dir;

function resolveKey(key) {
  // Guard against path traversal even though keys are generated by us.
  const full = path.resolve(root, key);
  if (!full.startsWith(path.resolve(root) + path.sep)) throw new Error('Invalid storage key');
  return full;
}

export async function saveFile(folder, buffer, ext = '') {
  const safeFolder = folder.replace(/[^a-z0-9_-]/gi, '');
  const key = `${safeFolder}/${crypto.randomUUID()}${ext}`;
  if (config.storage.driver === 'vercel-blob') {
    const blob = await put(key, buffer, { access: 'private', addRandomSuffix: false });
    return blob.pathname;
  }
  const full = resolveKey(key);
  await fs.mkdir(path.dirname(full), { recursive: true, mode: 0o700 });
  await fs.writeFile(full, buffer, { mode: 0o600 });
  return key;
}

export async function openStream(key) {
  if (config.storage.driver === 'vercel-blob') {
    const blob = await get(key, { access: 'private' });
    if (!blob || blob.statusCode !== 200 || !blob.stream) return null;
    return Readable.fromWeb(blob.stream);
  }
  return createReadStream(resolveKey(key));
}

export async function deleteFile(key) {
  if (config.storage.driver === 'vercel-blob') {
    try {
      await del(key);
    } catch (err) {
      if (!(err instanceof BlobNotFoundError)) throw err;
    }
    return;
  }
  try {
    await fs.unlink(resolveKey(key));
  } catch (e) {
    if (e.code !== 'ENOENT') throw e;
  }
}

export async function exists(key) {
  if (config.storage.driver === 'vercel-blob') {
    try {
      await head(key, { access: 'private' });
      return true;
    } catch (err) {
      if (err instanceof BlobNotFoundError) return false;
      throw err;
    }
  }
  try {
    await fs.access(resolveKey(key));
    return true;
  } catch {
    return false;
  }
}

export const extFor = (mime) =>
  ({
    'application/pdf': '.pdf',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document': '.docx',
    'image/jpeg': '.jpg',
    'image/png': '.png',
  })[mime] || '';
